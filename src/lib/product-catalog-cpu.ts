import { cpuParamsText } from "@/lib/cpu-spec";

function cpu(
  code: string,
  brand: "英特尔" | "AMD",
  name: string,
  spec: string,
  sale: number,
  cost: number,
  remark: string,
  stock = 2,
  warranty = 36,
) {
  return {
    code,
    name,
    brand,
    spec,
    unit: "个",
    cat: "PC-CPU",
    sale,
    cost,
    stock,
    warranty,
    canBeBuildPart: true,
    remark,
    params: cpuParamsText({ brand, name, spec, remark }),
    images: [] as string[],
  };
}

function boxed(
  code: string,
  brand: "英特尔" | "AMD",
  model: string,
  spec: string,
  sale: number,
  cost: number,
  remark: string,
  stock = 2,
) {
  return cpu(code, brand, `${model} 盒装`, spec, sale, cost, remark, stock, 36);
}

/** 散片/拆机：不带原装风扇，店保一年。 */
function tray(
  code: string,
  brand: "英特尔" | "AMD",
  model: string,
  spec: string,
  sale: number,
  cost: number,
  remark: string,
  stock = 2,
) {
  return cpu(
    code,
    brand,
    `${model} 散片`,
    `${spec} 散片无风扇`,
    sale,
    cost,
    `散片/拆机，店保一年，不带原装风扇。${remark}`,
    stock,
    12,
  );
}

