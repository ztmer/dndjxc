function gpu(
  code: string,
  brand: string,
  name: string,
  spec: string,
  sale: number,
  cost: number,
  remark: string,
  stock = 1,
) {
  return {
    code,
    name,
    brand,
    spec,
    unit: "块",
    cat: "PC-GPU",
    sale,
    cost,
    stock,
    warranty: 36,
    canBeBuildPart: true,
    remark,
    params: [
      `品牌：${brand}`,
      `型号：${name}`,
      `规格：${spec}`,
      "形态：台式机独立显卡，不含笔记本芯",
      remark,
    ].join("\n"),
    images: [] as string[],
  };
}

