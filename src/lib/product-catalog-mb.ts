function mb(
  code: string,
  brand: string,
  name: string,
  spec: string,
  sale: number,
  cost: number,
  remark: string,
  stock = 2,
) {
  return {
    code,
    name,
    brand,
    spec,
    unit: "块",
    cat: "PC-MB",
    sale,
    cost,
    stock,
    warranty: 36,
    canBeBuildPart: true,
    remark,
    params: [
      `品牌：${brand}`,
      `型号：${name}`,
      `规格：${spec}`,
      "形态：台式机主板",
      remark,
    ].join("\n"),
    images: [] as string[],
  };
}

